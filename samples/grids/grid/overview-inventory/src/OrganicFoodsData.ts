export type StorageType = 'Chilled' | 'Dry' | 'Ambient';

export type StockStatus = 'In stock' | 'Low' | 'Out of stock';

export interface OrganicFood {
    SKU: string;
    ProductName: string;
    Category: string;
    Supplier: string;
    Organic: boolean;
    Storage: StorageType;
    Quantity: number;
    /** Percent of the target stock, 0 to 100. */
    StockLevel: number;
    Unit: string;
    Status: StockStatus;
    UnitPrice: number;
    RetailPrice: number;
    ExpiryDate: Date;
    /** The product photo, as a data URI. */
    Image: string;
}

/** A date at local midnight, so the grid shows the same day in every time zone. */
function day(isoDate: string): Date {
    const [year, month, date] = isoDate.split('-').map(Number);
    return new Date(year, month - 1, date);
}

